// Writes demos/index.html and demos/<slug>/index.html from src/demos/catalogue.ts, so every page's title,
// description, preview tags, structured data, and no-JavaScript summary come from the demo's own definition.
// Run with `npm run pages`; tests/unit checks the committed files match.
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CATALOGUE, type CatalogueEntry, demoPath } from '../src/demos/catalogue.ts'

const ORIGIN = 'https://darkflib.com'
const ROOT = fileURLToPath(new URL('..', import.meta.url))

const escapeHtml = (text: string) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')

interface Page {
  /** Root-relative URL path, ending in a slash. */
  path: string
  /** Value of #root's data-page, which src/demos-main.tsx renders. */
  key: string
  title: string
  description: string
  jsonLd: object
  noscript: string
}

function render(page: Page): string {
  const url = `${ORIGIN}${page.path}`
  const title = escapeHtml(page.title)
  const description = escapeHtml(page.description)
  const jsonLd = JSON.stringify(page.jsonLd, null, 2).replaceAll('\n', '\n      ')
  return `<!doctype html>
<!-- Generated by scripts/demo-pages.ts from src/demos/catalogue.ts. Edit those, then run \`npm run pages\`. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#070b18" />
    <meta name="description" content="${description}" />
    <title>${title}</title>
    <link rel="canonical" href="${url}" />
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="sitemap" type="application/xml" href="/sitemap.xml" />
    <meta name="robots" content="index, follow, max-image-preview:large" />
    <meta name="author" content="Darkflib" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Darkflib" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${title}" />
    <meta property="og:description" content="${description}" />
    <meta property="og:image" content="${ORIGIN}/images/og-card.jpg" />
    <meta property="og:image:type" content="image/jpeg" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="A neon cyberpunk city skyline at night" />
    <meta property="og:locale" content="en_GB" />
    <meta name="twitter:card" content="summary_large_image" />
    <!-- A data block, not a script: script-src does not apply, so the CSP stays as it is. -->
    <script type="application/ld+json">
      ${jsonLd}
    </script>
  </head>
  <body>
    <div id="root" data-page="${page.key}"></div>
    <!-- For crawlers and unfurlers that do not run JavaScript, which otherwise see an empty page. -->
    <noscript>
${page.noscript}
    </noscript>
    <script type="module" src="/src/demos-main.tsx"></script>
  </body>
</html>
`
}

const indent = (lines: string[]) => lines.map((line) => `      ${line}`).join('\n')

function indexPage(): Page {
  return {
    path: '/demos/',
    key: 'index',
    title: 'DEMOS — DARKFLIB',
    description:
      'SRE and systems demos you can break on purpose: queueing, retry storms, circuit breakers, and failover, run in your own browser.',
    jsonLd: {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      '@id': `${ORIGIN}/demos/#page`,
      url: `${ORIGIN}/demos/`,
      name: 'Demos',
      description: 'SRE and systems demos you can break on purpose.',
      inLanguage: 'en',
      isPartOf: { '@id': `${ORIGIN}/#website` },
      author: { '@id': `${ORIGIN}/#person` },
      hasPart: CATALOGUE.map((entry) => ({ '@id': `${ORIGIN}${demoPath(entry.slug)}#page` })),
    },
    noscript: indent([
      '<h1>DEMOS</h1>',
      '<p>Reliability patterns you can break on purpose. The demos need JavaScript.</p>',
      '<ul>',
      ...CATALOGUE.map(
        (entry) =>
          `  <li><a href="${demoPath(entry.slug)}">${escapeHtml(entry.name)}</a>: ${escapeHtml(entry.question)}</li>`,
      ),
      '</ul>',
      '<p><a href="/">Darkflib home</a></p>',
    ]),
  }
}

function demoPage(entry: CatalogueEntry): Page {
  const url = `${ORIGIN}${demoPath(entry.slug)}`
  return {
    path: demoPath(entry.slug),
    key: entry.slug,
    title: `${entry.title} — DEMOS — DARKFLIB`,
    description: entry.summary,
    jsonLd: {
      '@context': 'https://schema.org',
      '@type': 'WebPage',
      '@id': `${url}#page`,
      url,
      name: entry.name,
      description: entry.summary,
      inLanguage: 'en',
      learningResourceType: entry.kind === 'live' ? 'Interactive demo' : 'Interactive simulation',
      keywords: entry.tags.map((tag) => tag.toLowerCase()).join(', '),
      isPartOf: { '@id': `${ORIGIN}/demos/#page` },
      author: { '@id': `${ORIGIN}/#person` },
    },
    noscript: indent([
      `<h1>${escapeHtml(entry.name)}</h1>`,
      `<p>${escapeHtml(entry.question)} ${escapeHtml(entry.summary)} The demo needs JavaScript.</p>`,
      ...entry.takeaways.flatMap((takeaway) => [
        `<h2>${escapeHtml(takeaway.title)}</h2>`,
        `<p>${escapeHtml(takeaway.body)}</p>`,
      ]),
      '<p><a href="/demos/">All demos</a></p>',
    ]),
  }
}

/** Every generated page, keyed by its file path relative to the repository root. */
export function demoPages(): Map<string, string> {
  const pages = [indexPage(), ...CATALOGUE.map(demoPage)]
  return new Map(pages.map((page) => [`demos${page.path.slice('/demos'.length)}index.html`, render(page)]))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, html] of demoPages()) {
    const target = `${ROOT}${file}`
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, html)
    console.log(`wrote ${file}`)
  }
}
