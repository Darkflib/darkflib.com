function allPages(): Page[] {
  return [projectsPage(), indexPage(), ...CATALOGUE.map(demoPage), ...accessPages()]
}

const fileOf = (page: Page) => `${page.path.slice(1)}index.html`

/** Every generated page, keyed by its file path relative to the repository root. */
export function sitePages(): Map<string, string> {
  return new Map(allPages().map((page) => [fileOf(page), render(page)]))
}

/** The URL path of every generated page, and whether it belongs in search and the sitemap. */
export function sitePaths(): { path: string; file: string; listed: boolean }[] {
  return allPages().map((page) => ({ path: page.path, file: fileOf(page), listed: page.listed ?? true }))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, html] of sitePages()) {
    const target = `${ROOT}${file}`
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, html)
    console.log(`wrote ${file}`)
  }
}
