// Writes the HTML for every page but the home page: projects/index.html from src/content.ts, demos/index.html
// and demos/<slug>/index.html from src/demos/catalogue.ts, and the access pages under login/ and tools/. Each page's title, description, preview tags, structured
// data, and no-JavaScript summary come from that source. Run with `npm run pages`; tests/unit checks the committed
// files match.
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PROJECTS_PATH, projects } from '../src/content.ts'
import { CATALOGUE, type CatalogueEntry, DEMO_GROUPS, demoPath } from '../src/demos/catalogue.ts'

const ORIGIN = 'https://darkflib.com'
const ROOT = fileURLToPath(new URL('..', import.meta.url))

const escapeHtml = (text: string) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')

interface Page {
  /** Root-relative URL path, ending in a slash. */
  path: string
  /** Value of #root's data-page, which the entry script renders. */
  key: string
  /** The page's entry script. */
  entry: '/src/demos-main.tsx' | '/src/projects-main.tsx' | '/src/login-main.tsx'
  /** Where the page's content is edited, for the generated-file notice. */
  source: string
  title: string
  description: string
  /** Structured data; none for pages kept out of search. */
  jsonLd?: object
  noscript: string
  /** False keeps the page out of search results and the sitemap. */
  listed?: boolean
}

function jsonLdBlock(data: object): string {
  const json = JSON.stringify(data, null, 2).replaceAll('\n', '\n      ')
  return `
    <!-- A data block, not a script: script-src does not apply, so the CSP stays as it is. -->
    <script type="application/ld+json">
      ${json}
    </script>`
}

function render(page: Page): string {
  const url = `${ORIGIN}${page.path}`
  const title = escapeHtml(page.title)
  const description = escapeHtml(page.description)
  const listed = page.listed ?? true
  return `<!doctype html>
<!-- Generated by scripts/pages.ts from ${page.source}. Edit those, then run \`npm run pages\`. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#070b18" />
    <meta name="description" content="${description}" />
    <title>${title}</title>
    <link rel="canonical" href="${url}" />
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="sitemap" type="application/xml" href="/sitemap.xml" />
    <meta name="robots" content="${listed ? 'index, follow, max-image-preview:large' : 'noindex, nofollow'}" />
    <meta name="author" content="Darkflib" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Darkflib" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${title}" />
    <meta property="og:description" content="${description}" />
    <meta property="og:image" content="${ORIGIN}/images/og-card.jpg" />
    <meta property="og:image:type" content="image/jpeg" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="A neon cyberpunk city skyline at night" />
    <meta property="og:locale" content="en_GB" />
    <meta name="twitter:card" content="summary_large_image" />${page.jsonLd ? jsonLdBlock(page.jsonLd) : ''}
  </head>
  <body>
    <div id="root" data-page="${page.key}"></div>
    <!-- For crawlers and unfurlers that do not run JavaScript, which otherwise see an empty page. -->
    <noscript>
${page.noscript}
    </noscript>
    <script type="module" src="${page.entry}"></script>
  </body>
</html>
`
}

const indent = (lines: string[]) => lines.map((line) => `      ${line}`).join('\n')

function projectsPage(): Page {
  return {
    path: PROJECTS_PATH,
    key: 'projects',
    entry: '/src/projects-main.tsx',
    source: 'src/content.ts',
    title: 'PROJECTS — DARKFLIB',
    description: `Things I have built: ${projects.map((project) => project.name.toLowerCase()).join(', ')}.`,
    jsonLd: {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      '@id': `${ORIGIN}${PROJECTS_PATH}#page`,
      url: `${ORIGIN}${PROJECTS_PATH}`,
      name: 'Projects',
      inLanguage: 'en',
      isPartOf: { '@id': `${ORIGIN}/#website` },
      author: { '@id': `${ORIGIN}/#person` },
      hasPart: projects.map((project) => ({
        '@type': 'SoftwareSourceCode',
        '@id': `${ORIGIN}${PROJECTS_PATH}#${project.slug}`,
        name: project.name,
        description: project.summary,
        ...(project.links.live ? { url: project.links.live } : {}),
        ...(project.links.source ? { codeRepository: project.links.source } : {}),
        keywords: project.tags.map((tag) => tag.toLowerCase()).join(', '),
      })),
    },
    noscript: indent([
      '<h1>PROJECTS</h1>',
      '<ul>',
      ...projects.map((project) => {
        const links = [
          project.links.live && `<a href="${project.links.live}">open</a>`,
          project.links.source && `<a href="${project.links.source}">source</a>`,
        ].filter(Boolean)
        const suffix = links.length ? ` (${links.join(', ')})` : ''
        return `  <li>${escapeHtml(project.name)}: ${escapeHtml(project.summary)}${suffix}</li>`
      }),
      '</ul>',
      '<p><a href="/">Darkflib home</a></p>',
    ]),
  }
}

